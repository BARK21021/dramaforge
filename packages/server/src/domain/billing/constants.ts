/**
 * 积分→元换算比例
 * 1 积分 = 0.1 元，即 1 元 = 10 积分
 *
 * 用途：
 * - estimateCost 将元费用转为积分时使用（total / CREDITS_TO_YUAN）
 * - credit/debit 写账本时将积分转回元（credits * CREDITS_TO_YUAN）
 */
export const CREDITS_TO_YUAN = 0.1;

/**
 * API 调用平台加价系数
 * 目录价 × 1.2 = 平台扣费价（20% 加价）
 *
 * 用途：
 * - estimateCost 在转积分前对 total 应用加价
 * - provider-balances 路由在生成价格标签时对目录价应用加价
 *
 * 设计原因：
 * 平台作为中间方代用户调用 AI 服务商 API，加价部分覆盖：
 * - 平台运维成本（服务器、带宽、监控）
 * - 支付通道手续费
 * - 风险准备金（坏账、退款）
 */
export const API_PRICE_MARKUP = 1.2;
